export const shortcutKeys = (shortcut: string) =>
  shortcut
    .split('+')
    .filter(Boolean)
    .map((s) => labels[s] || s.replace(/^Key|^Digit/, ''));
export function recordStroke(e: KeyStroke) {
  const modifiers = [
    e.ctrlKey && 'Control',
    e.altKey && 'Alt',
    e.shiftKey && 'Shift',
    e.metaKey && 'Command',
  ].filter(Boolean) as string[];
  const modifierOnly = /^(Meta|Control|Alt|Shift)/.test(e.code) || !e.code;
  const supported =
    /^(Key[A-Z]|Digit[0-9]|F([1-9]|1[0-9]|20))$/.test(e.code) ||
    [
      'Space',
      'Enter',
      'Tab',
      'Backspace',
      'Delete',
      'ArrowUp',
      'ArrowDown',
      'ArrowLeft',
      'ArrowRight',
      'Home',
      'End',
      'PageUp',
      'PageDown',
      'Minus',
      'Equal',
      'BracketLeft',
      'BracketRight',
      'Backslash',
      'Semicolon',
      'Quote',
      'Backquote',
      'Comma',
      'Period',
      'Slash',
    ].includes(e.code);
  const value = [...modifiers, ...(!modifierOnly && supported ? [e.code] : [])].join('+');
  if (modifierOnly) return { value, complete: false, error: '' };
  if (!supported) return { value, complete: false, error: 'Try another key.' };
  if (!e.metaKey && !e.ctrlKey && !e.altKey)
    return { value, complete: false, error: 'Include ⌘, ⌥, or ⌃.' };
  return { value, complete: true, error: '' };
}
