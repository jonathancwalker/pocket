export function nativeStroke(e: { code: number; flags: number; down: boolean }): KeyStroke {
  return {
    code: e.down ? macCodes[e.code] || 'Unsupported' : '',
    ctrlKey: !!(e.flags & 1),
    altKey: !!(e.flags & 2),
    shiftKey: !!(e.flags & 4),
    metaKey: !!(e.flags & 8),
  };
}
